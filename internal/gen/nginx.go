package gen

import (
	"fmt"
	"regexp"
	"strings"
	"time"

	"github.com/shivashis-adhikari/keyfold/internal/plan"
	"github.com/shivashis-adhikari/keyfold/internal/routes"
)

var nginxArgName = regexp.MustCompile(`^[A-Za-z0-9_]+$`)

// writes map blocks that compute $keyfold_cache_key. include the file
// inside http {} and set proxy_cache_key $keyfold_cache_key; where you
// proxy.
//
// safe mode removes dropped params from $args with one regex map per param,
// so params nobody has seen before stay in the key. nginx can't sort a query
// string without njs, so order still splits entries there. tight mode
// rebuilds the query from $arg_name for the kept params only.
func Nginx(p *plan.Plan, opts Options) ([]byte, []string, error) {
	var b strings.Builder
	var warns []string
	rs := routesToEmit(p)
	// map regexes are tried in order, first match wins
	for i, j := 0, len(rs)-1; i < j; i, j = i+1, j-1 {
		rs[i], rs[j] = rs[j], rs[i]
	}
	fmt.Fprintf(&b, "# cache keys generated by keyfold, %s, %s mode.\n", time.Now().UTC().Format("2006-01-02"), p.Mode)
	b.WriteString("# include inside http {}, then in the proxying location:\n")
	b.WriteString("#   proxy_cache_key $keyfold_cache_key;\n\n")

	var lang, device bool
	for _, r := range rs {
		lang = lang || r.Header.Lang
		device = device || r.Header.Device
		if r.Query.Sort && p.Mode != plan.Tight {
			warns = append(warns, fmt.Sprintf("nginx: %s could ignore param order, plain nginx can't sort a query string", r.Pattern))
		}
	}
	if lang {
		b.WriteString("map $http_accept_language $keyfold_lang {\n\t\"~^(?<kf_l>[A-Za-z]+)\" $kf_l;\n\tdefault \"\";\n}\n\n")
	}
	if device {
		b.WriteString("map $http_user_agent $keyfold_device {\n\t\"~*ipad|tablet\" tablet;\n\t\"~*mobi|iphone|ipod|android|blackberry|opera.mini\" mobile;\n\tdefault desktop;\n}\n\n")
	}

	route := "$uri"
	if opts.Canary {
		route = "$http_x_keyfold_canary:$uri"
	}
	fmt.Fprintf(&b, "map %s $keyfold_route {\n", route)
	for i, r := range rs {
		re := routes.Regex(r.Pattern)
		if opts.Canary {
			re = "^1:" + strings.TrimPrefix(re, "^")
		}
		fmt.Fprintf(&b, "\t%q r%d;\n", "~"+re, i)
	}
	b.WriteString("\tdefault \"\";\n}\n\n")

	keys := make([]string, len(rs))
	for i, r := range rs {
		args := "$args"
		if p.Mode == plan.Tight {
			var qs []string
			for _, q := range kept(r) {
				if !nginxArgName.MatchString(q) {
					warns = append(warns, fmt.Sprintf("nginx: param %q on %s has no $arg_ variable, left out of the key", q, r.Pattern))
					continue
				}
				qs = append(qs, q+"=$arg_"+q)
			}
			args = strings.Join(qs, "&")
		} else if len(r.Query.Drop) > 0 {
			args = nginxStripChain(&b, i, r.Query.Drop)
		}
		k := "$scheme://$host$uri"
		if args != "" {
			k += "?" + args
		}
		if r.Header.Lang {
			k += "|lang=$keyfold_lang"
		}
		if r.Header.Device {
			k += "|dev=$keyfold_device"
		}
		for _, h := range r.Header.Include {
			k += "|h:" + h + "=$http_" + strings.ReplaceAll(strings.ToLower(h), "-", "_")
		}
		for _, c := range r.Cookie.Include {
			k += "|c:" + c + "=$cookie_" + c
		}
		for _, c := range r.Cookie.Presence {
			warns = append(warns, fmt.Sprintf("nginx: %s keys on the full value of cookie %s, presence-only isn't expressible", r.Pattern, c))
			k += "|c:" + c + "=$cookie_" + c
		}
		if opts.Canary {
			k += "|canary"
		}
		keys[i] = k
	}

	b.WriteString("map $keyfold_route $keyfold_cache_key {\n")
	for i, k := range keys {
		fmt.Fprintf(&b, "\tr%d %q;\n", i, k)
	}
	b.WriteString("\tdefault \"$scheme://$host$request_uri\";\n}\n")
	return []byte(b.String()), warns, nil
}

// one map per dropped param, each removing the first occurrence from the
// previous step's args, then a last map that trims a leading '&'. returns
// the variable holding the result.
func nginxStripChain(b *strings.Builder, route int, drop []string) string {
	prev := "$args"
	for j, q := range drop {
		cur := fmt.Sprintf("$keyfold_r%d_a%d", route, j)
		fmt.Fprintf(b, "map %s %s {\n", prev, cur)
		fmt.Fprintf(b, "\t%q $kf_p$kf_s;\n", `~^(?<kf_p>.*?)(?:^|&)`+routes.QuoteMeta(q)+`(?:=[^&]*)?(?<kf_s>&.*)?$`)
		fmt.Fprintf(b, "\tdefault %s;\n}\n\n", prev)
		prev = cur
	}
	out := fmt.Sprintf("$keyfold_r%d_args", route)
	fmt.Fprintf(b, "map %s %s {\n\t\"~^&(?<kf_r>.*)$\" $kf_r;\n\tdefault %s;\n}\n\n", prev, out, prev)
	return out
}
