// writes a caddyfile for caddy built with the cache handler
// (github.com/caddyserver/cache-handler, souin underneath).
//
// safe mode strips the dropped params with `uri query` before the cache
// sees the request, so the default key (method, scheme, host, path, query)
// is already the planned key, and caddy re-encodes the query sorted as a
// side effect. tight mode leaves the request alone and builds the key from
// a template that names only the kept params.
//
// header and cookie key parts become x-keyfold-* request headers that the
// cache handler adds to the key. client-sent copies are deleted first, or
// anyone could pick their own cache entry.
func Caddy(p *plan.Plan, opts Options) ([]byte, []string, error) {
	var b strings.Builder
	var warns []string
	rs := routesToEmit(p)
	// cache_keys is first match, so most specific first
	for i, j := 0, len(rs)-1; i < j; i, j = i+1, j-1 {
		rs[i], rs[j] = rs[j], rs[i]
	}
	poisoned := len(reflectsForwardedHost(p)) > 0

	fmt.Fprintf(&b, "# cache keys generated by keyfold, %s, %s mode.\n", time.Now().UTC().Format("2006-01-02"), p.Mode)
	b.WriteString("# needs caddy with the cache handler:\n")
	b.WriteString("#   xcaddy build --with github.com/caddyserver/cache-handler\n")
	b.WriteString("# inside your site block, before reverse_proxy:\n")
	b.WriteString("#   import keyfold_cache\n\n")
	b.WriteString("{\n\tcache {\n\t\tttl 300s\n\t}\n}\n\n")
	b.WriteString("(keyfold_cache) {\n\troute {\n")

	var lang, device bool
	for _, r := range rs {
		lang = lang || r.Header.Lang
		device = device || r.Header.Device
	}
	b.WriteString("\t\trequest_header -X-Keyfold-*\n")
	if poisoned {
		b.WriteString("\t\t# the origin reflects this header into pages, see the plan's flags\n")
		b.WriteString("\t\trequest_header -X-Forwarded-Host\n")
	}
	if lang {
		b.WriteString("\t\tmap {http.request.header.Accept-Language} {kf_lang} {\n")
		b.WriteString("\t\t\t~^([A-Za-z]+) \"${1}\"\n\t\t\tdefault \"\"\n\t\t}\n")
	}
	if device {
		b.WriteString("\t\tmap {http.request.header.User-Agent} {kf_device} {\n")
		b.WriteString("\t\t\t~(?i)ipad|tablet tablet\n")
		b.WriteString("\t\t\t~(?i)mobi|iphone|ipod|android|blackberry|opera.mini mobile\n")
		b.WriteString("\t\t\tdefault desktop\n\t\t}\n")
	}

	type override struct {
		re   string
		body []string
	}
	var overrides []override
	for i, r := range rs {
		m := fmt.Sprintf("kf%d", i)
		fmt.Fprintf(&b, "\n\t\t# %s\n", strings.TrimSpace(r.Host+" "+r.Pattern))
		fmt.Fprintf(&b, "\t\t@%s {\n", m)
		if r.Host != "" {
			fmt.Fprintf(&b, "\t\t\thost %s\n", r.Host)
		}
		fmt.Fprintf(&b, "\t\t\tpath_regexp %s %s\n", m, routes.Regex(r.Pattern))
		if opts.Canary {
			fmt.Fprintf(&b, "\t\t\theader %s 1\n", CanaryHeader)
		}
		b.WriteString("\t\t}\n")

		var parts []string
		var setHeaders [][2]string
		if r.Header.Lang {
			setHeaders = append(setHeaders, [2]string{"X-Keyfold-Lang", "{kf_lang}"})
		}
		if r.Header.Device {
			setHeaders = append(setHeaders, [2]string{"X-Keyfold-Device", "{kf_device}"})
		}
		for _, h := range r.Header.Include {
			setHeaders = append(setHeaders, [2]string{"X-Keyfold-H-" + headerName(h), "{http.request.header." + headerName(h) + "}"})
		}
		for _, c := range r.Cookie.Include {
			setHeaders = append(setHeaders, [2]string{"X-Keyfold-C-" + headerName(c), "{http.request.cookie." + c + "}"})
		}
		for _, c := range r.Cookie.Presence {
			// caddy has no "is this cookie set" placeholder. the value with
			// a fixed prefix is the closest, and keys on value too.
			warns = append(warns, fmt.Sprintf("caddy: %s keys on the full value of cookie %s, presence-only isn't expressible", r.Pattern, c))
			setHeaders = append(setHeaders, [2]string{"X-Keyfold-C-" + headerName(c), "{http.request.cookie." + c + "}"})
		}
		if opts.Canary {
			setHeaders = append(setHeaders, [2]string{"X-Keyfold-Canary-Key", "1"})
		}
		for _, h := range setHeaders {
			fmt.Fprintf(&b, "\t\trequest_header @%s %s %q\n", m, h[0], h[1])
			parts = append(parts, h[0])
		}

		re := cacheKeyRegex(r)
		var body []string
		if p.Mode == plan.Tight {
			t := "{http.request.method}-{http.request.scheme}-{http.request.host}{http.request.uri.path}"
			for j, q := range kept(r) {
				sep := "&"
				if j == 0 {
					sep = "?"
				}
				t += sep + q + "={http.request.uri.query." + q + "}"
			}
			for _, h := range parts {
				t += "-{http.request.header." + h + "}"
			}
			body = append(body, fmt.Sprintf("template %q", t))
		} else {
			if len(r.Query.Drop) > 0 {
				fmt.Fprintf(&b, "\t\turi @%s query {\n", m)
				for _, q := range r.Query.Drop {
					fmt.Fprintf(&b, "\t\t\t-%s\n", q)
				}
				b.WriteString("\t\t}\n")
			}
			if r.Query.Sort {
				body = append(body, "sort_query")
			}
			if len(parts) > 0 {
				body = append(body, "headers "+strings.Join(parts, " "))
			}
		}
		if len(body) > 0 {
			overrides = append(overrides, override{re, body})
		}
	}

	b.WriteString("\n\t\tcache {\n")
	if len(overrides) > 0 {
		b.WriteString("\t\t\tcache_keys {\n")
		for _, o := range overrides {
			fmt.Fprintf(&b, "\t\t\t\t%s {\n", o.re)
			for _, line := range o.body {
				fmt.Fprintf(&b, "\t\t\t\t\t%s\n", line)
			}
			b.WriteString("\t\t\t\t}\n")
		}
		b.WriteString("\t\t\t}\n")
	}
	b.WriteString("\t\t}\n\t}\n}\n")
	return []byte(b.String()), warns, nil
}

// the cache handler matches cache_keys patterns against the request uri,
// query included, so the path regex has to allow for one.
func cacheKeyRegex(r *plan.Route) string {
	re := strings.TrimSuffix(routes.Regex(r.Pattern), "$")
	re = strings.ReplaceAll(re, `[^/]+`, `[^/?]+`)
	return re + `([?]|$)`
}

var headerNameRe = regexp.MustCompile(`[^A-Za-z0-9-]+`)

func headerName(s string) string {
	parts := strings.Split(headerNameRe.ReplaceAllString(s, "-"), "-")
	for i, p := range parts {
		if p != "" {
			parts[i] = strings.ToUpper(p[:1]) + strings.ToLower(p[1:])
		}
	}
	return strings.Join(parts, "-")
}
